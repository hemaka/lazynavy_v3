export function translateSourceText(locale: UiLocale, source: string, vars?: Record<string, string | number>): string {
  let text = locale === 'zh-CN' || locale === 'zh-TW' ? source : SOURCE_TEXT_EN[source] ?? source
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value))
    }
  }
  return text
}
